export const translationsMap: Record<Language, Translations> = {
  English: english,
  Tamil: tamil,
  Hindi: hindi,
  Telugu: telugu,
  Kannada: kannada,
  Malayalam: malayalam,
  Bengali: bengali,
  Marathi: marathi,
};

export const getTranslationKeys = () => Object.keys(english) as Array<keyof Translations>;

export const translate = (
  language: Language | string,
  key: string,
  replacements?: Record<string, string | number>
): string => {
  const safeLang: Language =
    (SUPPORTED_LANGS as readonly string[]).includes(language as string)
      ? (language as Language)
      : 'English';
  const t: Translations = translationsMap[safeLang] || english;
  const parts = key.split('.');
  let value: any = t;
  for (const p of parts) {
    if (value && typeof value === 'object' && p in value) value = value[p];
    else return key;
  }
  let str = typeof value === 'string' ? value : key;
  if (replacements) {
    for (const [k, v] of Object.entries(replacements)) {
      str = str.split(`{${k}}`).join(String(v));
    }
  }
  return str;
};
